"""
Integration tests that verify Python can consume data generated by the Rust pipeline.

These tests:
  1. Load every tenant in examples/tenants/ (including Rust-generated ones) and
     verify TenantConfig parsing succeeds without validation errors.
  2. Run a real embedding+index cycle against the Azure API to confirm the full
     chain works end-to-end.  Skipped when AZURE_API_KEY is absent.
"""

import asyncio
import os
import pytest

from src.config.tenant_config import TenantConfig
from src.core.embedding_provider import AzureEmbeddingProvider, MockEmbeddingProvider
from src.core.search_engine import SearchEngine
from src.sandbox.local_sandbox import LocalSandbox

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TENANTS_DIR = os.path.join(REPO_ROOT, "examples", "tenants")


def _tenant_dirs():
    if not os.path.isdir(TENANTS_DIR):
        return []
    return sorted(
        d for d in os.listdir(TENANTS_DIR)
        if os.path.isdir(os.path.join(TENANTS_DIR, d))
        and os.path.isfile(os.path.join(TENANTS_DIR, d, "tenant.yaml"))
    )


# ---------------------------------------------------------------------------
# Schema compatibility tests (no network required)
# ---------------------------------------------------------------------------

class TestRustGeneratedTenantParsing:
    """All tenants in examples/tenants/ must parse cleanly into TenantConfig."""

    @pytest.mark.parametrize("tenant_dir", _tenant_dirs())
    def test_tenant_parses_ok(self, tenant_dir):
        path = os.path.join(TENANTS_DIR, tenant_dir, "tenant.yaml")
        cfg = TenantConfig.from_yaml(path)
        assert cfg.id, f"{tenant_dir}: id must be non-empty"
        assert isinstance(cfg.users, list)
        assert isinstance(cfg.emails, list)

    @pytest.mark.parametrize("tenant_dir", _tenant_dirs())
    def test_all_timestamps_are_strings(self, tenant_dir):
        """Datetime objects must have been coerced to ISO strings."""
        path = os.path.join(TENANTS_DIR, tenant_dir, "tenant.yaml")
        cfg = TenantConfig.from_yaml(path)
        for fm in cfg.files_metadata:
            for field in (fm.created_time, fm.last_modified_time):
                if field is not None:
                    assert isinstance(field, str), f"{tenant_dir}: FileMetadata time must be str"
        for email in cfg.emails:
            assert isinstance(email.timestamp, str), f"{tenant_dir}: Email.timestamp must be str"
        for chat in cfg.chats:
            for msg in chat.messages:
                assert isinstance(msg.timestamp, str)
        for meeting in cfg.meetings:
            assert isinstance(meeting.start_time, str)
            assert isinstance(meeting.end_time, str)

    @pytest.mark.parametrize("tenant_dir", _tenant_dirs())
    def test_mock_indexing_succeeds(self, tenant_dir):
        """Mock-embedding index_all must succeed for every tenant (no network needed)."""
        path = os.path.join(TENANTS_DIR, tenant_dir, "tenant.yaml")
        cfg = TenantConfig.from_yaml(path)
        emb = MockEmbeddingProvider()
        sandbox = LocalSandbox(cfg)
        sandbox.start()
        engine = SearchEngine(cfg, emb, sandbox)
        asyncio.run(engine.index_all())
        # At least one index should have been populated (unless tenant has no data)
        total = sum(len(v["data"]) for v in engine.indices.values())
        # Tenants with users should index at least the user records
        if cfg.users:
            assert total > 0


# ---------------------------------------------------------------------------
# Azure integration tests (require real keys, skip if absent)
# ---------------------------------------------------------------------------

def _azure_env():
    return {
        "api_key": os.getenv("AZURE_API_KEY"),
        "azure_endpoint": os.getenv("AZURE_ENDPOINT"),
        "api_version": os.getenv("AZURE_EMB_API_VERSION") or os.getenv("AZURE_API_VERSION"),
        "deployment_name": "text-embedding-ada-002",
    }


pytestmark_azure = pytest.mark.skipif(
    not os.getenv("AZURE_API_KEY"),
    reason="AZURE_API_KEY not set – skipping Azure integration tests",
)


@pytestmark_azure
class TestAzureEmbeddingIntegration:
    def test_single_embedding(self):
        env = _azure_env()
        provider = AzureEmbeddingProvider(**env)
        vec = asyncio.run(provider.get_embedding("hello world"))
        assert isinstance(vec, list)
        assert len(vec) > 0
        assert all(isinstance(x, float) for x in vec)

    def test_embedding_dimensionality_consistent(self):
        env = _azure_env()
        provider = AzureEmbeddingProvider(**env)
        v1 = asyncio.run(provider.get_embedding("first sentence"))
        v2 = asyncio.run(provider.get_embedding("second sentence"))
        assert len(v1) == len(v2)

    @pytest.mark.parametrize("tenant_dir", _tenant_dirs()[:1])  # only first tenant to save quota
    def test_azure_index_all(self, tenant_dir):
        """Full Azure embedding index round-trip on the first available tenant."""
        path = os.path.join(TENANTS_DIR, tenant_dir, "tenant.yaml")
        cfg = TenantConfig.from_yaml(path)
        env = _azure_env()
        provider = AzureEmbeddingProvider(**env)
        sandbox = LocalSandbox(cfg)
        sandbox.start()
        engine = SearchEngine(cfg, provider, sandbox)
        # Skip cache so we actually exercise the network
        engine.indices = {k: {"vectors": [], "data": []} for k in engine.indices}
        asyncio.run(engine.index_all())
        if cfg.users:
            assert len(engine.indices["users"]["data"]) == len(cfg.users)
